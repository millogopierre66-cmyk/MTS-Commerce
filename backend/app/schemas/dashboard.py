from pydantic import BaseModel


# ==========================================================
# RÉPONSE DU TABLEAU DE BORD
# ==========================================================

class DashboardResponse(BaseModel):

    # ======================================================
    # PRODUITS
    # ======================================================

    total_products: int

    # ======================================================
    # VENTES
    # ======================================================

    total_sales: int

    # ======================================================
    # CHIFFRE D'AFFAIRES
    # ======================================================

    total_revenue: float

    # ======================================================
    # STOCK
    # ======================================================

    stock_value: float

    total_movements: int

    # ======================================================
    # ALERTES STOCK
    # ======================================================

    out_of_stock: int

    low_stock: int